export function createTranslator(language = 'en') {
    const zh = /^zh(?:[-_]|$)/i.test(language);
    return (source, values = {}) => (zh ? chinese[source] ?? source : source)
        .replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
